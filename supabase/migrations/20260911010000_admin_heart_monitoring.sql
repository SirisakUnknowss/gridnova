CREATE OR REPLACE FUNCTION public.get_admin_hearts_overview()
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_result json;
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.user_roles WHERE user_id = auth.uid() AND role = 'admin'
  ) THEN
    RETURN json_build_object('error', 'forbidden');
  END IF;

  SELECT json_build_object(
    'current', (
      SELECT json_build_object(
        'tracked_members', COALESCE(COUNT(*), 0),
        'full_hearts', COALESCE(COUNT(*) FILTER (WHERE hearts = 5), 0),
        'zero_hearts', COALESCE(COUNT(*) FILTER (WHERE hearts = 0), 0),
        'low_hearts', COALESCE(COUNT(*) FILTER (WHERE hearts BETWEEN 1 AND 2), 0),
        'avg_hearts', COALESCE(ROUND(AVG(hearts)::numeric, 2), 0),
        'infinite_active', COALESCE(COUNT(*) FILTER (WHERE infinite_until > now()), 0)
      )
      FROM public.user_hearts
    ),
    'events_today', (
      SELECT json_build_object(
        'consumes', COALESCE(COUNT(*) FILTER (WHERE event_type = 'consume'), 0),
        'refunds', COALESCE(COUNT(*) FILTER (WHERE event_type = 'refund'), 0),
        'blocked', COALESCE(COUNT(*) FILTER (WHERE event_type = 'blocked_no_hearts'), 0),
        'infinite_starts', COALESCE(COUNT(*) FILTER (WHERE event_type = 'infinite_start'), 0),
        'buff_purchases', COALESCE(COUNT(*) FILTER (WHERE event_type = 'buy_infinite'), 0),
        'unique_users', COALESCE(COUNT(DISTINCT user_id), 0)
      )
      FROM public.heart_events
      WHERE created_at >= date_trunc('day', now() AT TIME ZONE 'Asia/Bangkok') AT TIME ZONE 'Asia/Bangkok'
    ),
    'by_mode_today', COALESCE((
      SELECT json_agg(row_to_json(m) ORDER BY m.consumes DESC, m.mode)
      FROM (
        SELECT
          COALESCE(mode, 'unknown') AS mode,
          COUNT(*) FILTER (WHERE event_type = 'consume') AS consumes,
          COUNT(*) FILTER (WHERE event_type = 'blocked_no_hearts') AS blocked,
          COUNT(*) FILTER (WHERE event_type = 'infinite_start') AS infinite_starts,
          COUNT(DISTINCT user_id) AS users
        FROM public.heart_events
        WHERE created_at >= date_trunc('day', now() AT TIME ZONE 'Asia/Bangkok') AT TIME ZONE 'Asia/Bangkok'
          AND event_type IN ('consume', 'blocked_no_hearts', 'infinite_start')
        GROUP BY COALESCE(mode, 'unknown')
      ) m
    ), '[]'::json),
    'current_rows', COALESCE((
      SELECT json_agg(row_to_json(r) ORDER BY r.hearts ASC, r.infinite_active DESC, r.updated_at DESC)
      FROM (
        SELECT
          h.user_id,
          COALESCE(p.display_name, p.username, 'Member') AS display_name,
          p.username,
          h.hearts,
          h.last_regen_at,
          h.infinite_until,
          h.infinite_until > now() AS infinite_active,
          h.updated_at
        FROM public.user_hearts h
        LEFT JOIN public.profiles p ON p.id = h.user_id
        ORDER BY h.hearts ASC, h.infinite_until > now() DESC, h.updated_at DESC
        LIMIT 50
      ) r
    ), '[]'::json)
  )
  INTO v_result;

  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION public.get_admin_heart_events(p_limit int DEFAULT 100)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM public.user_roles WHERE user_id = auth.uid() AND role = 'admin'
  ) THEN
    RETURN json_build_object('error', 'forbidden');
  END IF;

  RETURN COALESCE((
    SELECT json_agg(row_to_json(r) ORDER BY r.created_at DESC)
    FROM (
      SELECT
        e.id,
        e.user_id,
        COALESCE(p.display_name, p.username, 'Member') AS display_name,
        p.username,
        e.event_type,
        e.mode,
        e.hearts_before,
        e.hearts_after,
        e.infinite_until,
        e.metadata,
        e.created_at
      FROM public.heart_events e
      LEFT JOIN public.profiles p ON p.id = e.user_id
      ORDER BY e.created_at DESC
      LIMIT LEAST(GREATEST(COALESCE(p_limit, 100), 1), 500)
    ) r
  ), '[]'::json);
END;
$$;

