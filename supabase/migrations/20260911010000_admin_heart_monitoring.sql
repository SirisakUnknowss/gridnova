-- =====================================================================
-- Admin heart monitoring
-- =====================================================================
-- Adds an append-only event stream for member heart activity and admin RPCs
-- for the dashboard. Guest hearts are local-only by design, so this captures
-- authenticated members only.

CREATE TABLE IF NOT EXISTS public.heart_events (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id        uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  event_type     text NOT NULL CHECK (event_type IN (
    'consume',
    'refund',
    'blocked_no_hearts',
    'buy_infinite',
    'refill_full',
    'infinite_start'
  )),
  mode           text,
  hearts_before  int,
  hearts_after   int,
  infinite_until timestamptz,
  metadata       jsonb NOT NULL DEFAULT '{}'::jsonb,
  created_at     timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE public.heart_events ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "admin read heart events" ON public.heart_events;
CREATE POLICY "admin read heart events" ON public.heart_events
  FOR SELECT USING (
    EXISTS (
      SELECT 1 FROM public.user_roles
      WHERE user_id = auth.uid() AND role = 'admin'
    )
  );

CREATE INDEX IF NOT EXISTS heart_events_created_at_idx
  ON public.heart_events (created_at DESC);

CREATE INDEX IF NOT EXISTS heart_events_user_created_idx
  ON public.heart_events (user_id, created_at DESC);

CREATE INDEX IF NOT EXISTS heart_events_type_created_idx
  ON public.heart_events (event_type, created_at DESC);

CREATE OR REPLACE FUNCTION public._log_heart_event(
  p_user_id uuid,
  p_event_type text,
  p_mode text DEFAULT NULL,
  p_hearts_before int DEFAULT NULL,
  p_hearts_after int DEFAULT NULL,
  p_infinite_until timestamptz DEFAULT NULL,
  p_metadata jsonb DEFAULT '{}'::jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
BEGIN
  INSERT INTO public.heart_events (
    user_id,
    event_type,
    mode,
    hearts_before,
    hearts_after,
    infinite_until,
    metadata
  )
  VALUES (
    p_user_id,
    p_event_type,
    p_mode,
    p_hearts_before,
    p_hearts_after,
    p_infinite_until,
    COALESCE(p_metadata, '{}'::jsonb)
  );
END;
$$;

REVOKE EXECUTE ON FUNCTION public._log_heart_event(uuid, text, text, int, int, timestamptz, jsonb) FROM PUBLIC;

CREATE OR REPLACE FUNCTION public.consume_heart(p_mode text DEFAULT NULL)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_uid      uuid := auth.uid();
  v_row      public.user_hearts;
  v_before   int;
  v_infinite boolean;
BEGIN
  IF v_uid IS NULL THEN
    RETURN json_build_object('ok', false, 'reason', 'not_authenticated');
  END IF;
  v_row := _refresh_hearts(v_uid);
  v_before := v_row.hearts;
  v_infinite := v_row.infinite_until IS NOT NULL AND v_row.infinite_until > now();

  IF v_infinite THEN
    PERFORM public._log_heart_event(v_uid, 'infinite_start', p_mode, v_before, v_row.hearts, v_row.infinite_until);
    RETURN json_build_object('ok', true, 'consumed', false, 'hearts', v_row.hearts,
                             'infinite', true, 'infinite_until', v_row.infinite_until);
  END IF;

  IF v_row.hearts <= 0 THEN
    PERFORM public._log_heart_event(v_uid, 'blocked_no_hearts', p_mode, v_before, 0, NULL);
    RETURN json_build_object('ok', false, 'reason', 'no_hearts', 'hearts', 0,
                             'consumed', false, 'infinite', false,
                             'last_regen_at', v_row.last_regen_at);
  END IF;

  UPDATE user_hearts
    SET hearts = hearts - 1,
        last_regen_at = CASE WHEN hearts = 5 THEN now() ELSE last_regen_at END,
        updated_at = now()
    WHERE user_id = v_uid
    RETURNING * INTO v_row;

  PERFORM public._log_heart_event(v_uid, 'consume', p_mode, v_before, v_row.hearts, NULL);

  RETURN json_build_object('ok', true, 'consumed', true, 'hearts', v_row.hearts,
                           'infinite', false, 'last_regen_at', v_row.last_regen_at);
END;
$$;

CREATE OR REPLACE FUNCTION public.refund_heart()
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_uid uuid := auth.uid();
  v_row public.user_hearts;
  v_before int;
BEGIN
  IF v_uid IS NULL THEN
    RETURN json_build_object('ok', false, 'reason', 'not_authenticated');
  END IF;
  v_row := _refresh_hearts(v_uid);
  v_before := v_row.hearts;
  UPDATE user_hearts SET hearts = LEAST(5, hearts + 1), updated_at = now()
    WHERE user_id = v_uid
    RETURNING * INTO v_row;
  PERFORM public._log_heart_event(v_uid, 'refund', NULL, v_before, v_row.hearts, v_row.infinite_until);
  RETURN json_build_object('ok', true, 'hearts', v_row.hearts);
END;
$$;

CREATE OR REPLACE FUNCTION public.buy_infinite_hearts(p_hours int)
RETURNS json
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public'
AS $$
DECLARE
  v_uid   uuid := auth.uid();
  v_price int;
  v_spend jsonb;
  v_base  timestamptz;
  v_row   public.user_hearts;
  v_before int;
BEGIN
  IF v_uid IS NULL THEN
    RETURN json_build_object('ok', false, 'reason', 'not_authenticated');
  END IF;

  v_price := CASE p_hours
    WHEN 1 THEN 800
    WHEN 2 THEN 1400
    WHEN 3 THEN 1900
    WHEN 5 THEN 2800
    ELSE NULL
  END;
  IF v_price IS NULL THEN
    RETURN json_build_object('ok', false, 'reason', 'bad_hours');
  END IF;

  v_spend := spend_coins(v_uid, v_price, 'infinite_hearts',
                         jsonb_build_object('hours', p_hours));
  IF NOT COALESCE((v_spend->>'ok')::boolean, false) THEN
    RETURN json_build_object('ok', false,
                             'reason', COALESCE(v_spend->>'reason', 'insufficient_coins'),
                             'balance', (v_spend->>'balance')::int);
  END IF;

  v_row := _refresh_hearts(v_uid);
  v_before := v_row.hearts;
  v_base := GREATEST(now(), COALESCE(v_row.infinite_until, now()));
  UPDATE user_hearts
    SET infinite_until = v_base + (p_hours || ' hours')::interval, updated_at = now()
    WHERE user_id = v_uid
    RETURNING * INTO v_row;

  PERFORM public._log_heart_event(
    v_uid,
    'buy_infinite',
    NULL,
    v_before,
    v_row.hearts,
    v_row.infinite_until,
    jsonb_build_object('hours', p_hours, 'price', v_price, 'balance', (v_spend->>'balance')::int)
  );

  RETURN json_build_object('ok', true, 'infinite_until', v_row.infinite_until,
                           'hearts', v_row.hearts, 'balance', (v_spend->>'balance')::int);
END;
$$;

